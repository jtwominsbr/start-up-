// Format utilities
export function formatKrw(amount: number): string {
  return `₩${Math.round(amount).toLocaleString('ko-KR')}`;
}

export function formatJpy(amount: number): string {
  return `¥${Math.round(amount).toLocaleString('ko-KR')}`;
}

export function formatDualCurrency(krw: number, jpyRate = 9.0): { krwStr: string; jpyStr: string } {
  const jpy = Math.round(krw / jpyRate);
  return {
    krwStr: formatKrw(krw),
    jpyStr: formatJpy(jpy),
  };
}

export function formatDateKorean(dateStr: string): string {
  // '2026-10-12' -> '2026년 10월 12일'
  const parts = dateStr.split('-');
  if (parts.length === 3) {
    return `${parts[0]}년 ${parseInt(parts[1], 10)}월 ${parseInt(parts[2], 10)}일`;
  }
  return dateStr;
}

export function formatDateDot(dateStr: string): string {
  // '2026-10-12' -> '2026.10.12'
  return dateStr.replace(/-/g, '.');
}

